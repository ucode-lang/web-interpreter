/* ------------------------------------------------------------------ */
/* Output capture                                                      */
/*                                                                     */
/* ucode's print() writes to `vm->output` (a FILE*). We point that at   */
/* an open_memstream()-backed FILE* whose contents live in a plain C   */
/* buffer. After each run we copy that buffer into out_buf and expose   */
/* it to JS. This sidesteps emscripten's TTY/stdout entirely, which is  */
/* unreliable for C-level writes after the module's initial run.       */
/*                                                                     */
/* There are two independent capture streams:                          */
/*   console - what print()/errors produce during a normal run         */
/*   render  - what a template run produces; vm->output is temporarily  */
/*             diverted here so that a template's output can be handed   */
/*             to JS separately from the log (a template that itself    */
/*             calls print() still ends up in the rendered document,    */
/*             exactly like `ucode -T` on the command line).            */
/* ------------------------------------------------------------------ */

typedef struct {
	char *mem;
	size_t sz;
	FILE *file;
	struct printbuf *buf;
} capture_t;

static capture_t cap_console = { NULL, 0, NULL, NULL };
static capture_t cap_render = { NULL, 0, NULL, NULL };

/* Backwards-compatible aliases for the console stream. */
#define captured_file cap_console.file

static void
capture_init(capture_t *cap)
{
	if (cap->file)
		return;

	cap->buf = printbuf_new();
	cap->file = open_memstream(&cap->mem, &cap->sz);
}

/* Copy whatever ucode wrote into the memstream into the printbuf and reset
 * the memstream so the next run starts fresh. */
static void
capture_collect(capture_t *cap)
{
	if (!cap->file || !cap->buf)
		return;

	fflush(cap->file);

	if (cap->sz > 0 && cap->mem) {
		printbuf_memappend(cap->buf, cap->mem, (int)cap->sz);
		/* Reset the memstream: seek back to 0 so subsequent writes
		 * overwrite the same region and cap->sz restarts. */
		rewind(cap->file);
		cap->sz = 0;
	}
}

static void
capture_clear(capture_t *cap)
{
	if (cap->buf) {
		cap->buf->bpos = 0;
		cap->buf->buf[0] = '\0';
	}
}

/* Materialise a capture stream into a NUL-terminated, growable static
 * buffer suitable for handing to JS's UTF8ToString(). */
static char *
capture_string(capture_t *cap, char **bufp, size_t *capp)
{
	size_t len = cap->buf ? (size_t)cap->buf->bpos : 0;

	if (len + 1 > *capp) {
		*capp = len + 4096;
		*bufp = realloc(*bufp, *capp);
	}

	if (*bufp == NULL) {
		*capp = 0;
		return (char *)"";
	}

	if (len > 0)
		memcpy(*bufp, cap->buf->buf, len);

	(*bufp)[len] = '\0';

	return *bufp;
}

static char *out_str = NULL;
static size_t out_str_cap = 0;
static char *render_str = NULL;
static size_t render_str_cap = 0;

