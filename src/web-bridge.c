/*
 * Compile `source` under the given mode. Template mode is a property of the
 * source file, not of the VM, so the flags are flipped on the (static,
 * VM-referenced) parse config just for the duration of the compile and
 * restored afterwards -- uc_compile() hands the config to the lexer, which
 * must not outlive the call.
 */
static uc_program_t *
compile_source(uc_source_t *src, bool template_mode, char **errp)
{
	bool raw = vm_config.raw_mode, ls = vm_config.lstrip_blocks, tb = vm_config.trim_blocks;
	uc_program_t *prog;

	if (template_mode) {
		vm_config.raw_mode = false;
		vm_config.lstrip_blocks = true;
		vm_config.trim_blocks = true;
	}

	prog = uc_compile(vm.config, src, errp);

	vm_config.raw_mode = raw;
	vm_config.lstrip_blocks = ls;
	vm_config.trim_blocks = tb;

	return prog;
}

/*
 * Run `source` (NUL-terminated) as a program.
 *
 * `name` is used as the source name so that diagnostics -- and, more
 * importantly, the runpath used to resolve relative include()/import()
 * -- point at the pen file rather than at "[-e]".
 *
 * uc_source_new_buffer() takes ownership of the buffer it is handed and
 * free()s it when the source object is released (types.c), so the buffer
 * passed to it must be heap memory owned by ucode. Callers hand us
 * pointers into wasm memory that JS owns (and frees), so copy first.
 */
static void
run_source_named(const char *name, const char *source, bool is_expr, bool template_mode)
{
	uc_source_t *src;
	uc_program_t *prog;
	char *err = NULL, *copy;
	uc_value_t *res = NULL;
	uc_vm_status_t status;

	last_error[0] = '\0';

	copy = strdup(source ? source : "\n");

	if (!copy) {
		snprintf(last_error, sizeof(last_error), "out of memory");
		return;
	}

	src = uc_source_new_buffer(name, copy, strlen(copy));

	if (!src) {
		free(copy);
		snprintf(last_error, sizeof(last_error), "failed to create source buffer");
		return;
	}

	prog = compile_source(src, template_mode, &err);
	uc_source_put(src);

	if (!prog) {
		snprintf(last_error, sizeof(last_error), "%s", err ? err : "compile error");
		free(err);
		return;
	}

	status = uc_vm_execute(&vm, prog, &res);

	switch (status) {
	case STATUS_OK:
		if (is_expr && res) {
			FILE *out = vm.output ? vm.output : stdout;

			if (ucv_type(res) == UC_STRING) {
				fwrite(ucv_string_get(res), ucv_string_length(res), 1, out);
				fputc('\n', out);
			} else {
				uc_stringbuf_t *pb = xprintbuf_new();

				ucv_to_stringbuf_formatted(&vm, pb, res, 0, '\t', 1);
				fwrite(pb->buf, pb->bpos, 1, out);
				fputc('\n', out);
				printbuf_free(pb);
			}
		}
		break;

	case STATUS_EXIT:
		break;

	case STATUS_BREAK:
		break;

	case ERROR_COMPILE:
	case ERROR_RUNTIME:
		{
			uc_value_t *exobj = uc_vm_exception_object(&vm);

			if (exobj) {
				uc_stringbuf_t *pb = xprintbuf_new();

				ucv_to_stringbuf_formatted(&vm, pb, exobj, 0, '\t', 1);
				snprintf(last_error, sizeof(last_error), "%s", pb->buf);
				printbuf_free(pb);
				ucv_put(exobj);
			}
		}
		break;
	}

	if (res)
		ucv_put(res);

	uc_program_put(prog);
}

static void
run_source(const char *source, bool is_expr)
{
	run_source_named("[-e]", source, is_expr, false);
}

/* Read a whole file into a freshly malloc'd NUL-terminated buffer, or
 * NULL. Caller frees. */
static char *
file_read_owned(const char *path, size_t *lenp)
{
	static const size_t chunk = 65536;
	char *buf = NULL, *tmp;
	size_t len = 0, n;
	FILE *f;

	f = fopen(path, "rb");

	if (!f)
		return NULL;

	while ((len % chunk) == 0 || len == 0) {
		tmp = realloc(buf, len + chunk);

		if (!tmp)
			break;

		buf = tmp;
		n = fread(buf + len, 1, chunk - (len % chunk), f);
		len += n;

		if (n == 0)
			break;
	}

	fclose(f);

	if (!buf)
		return NULL;

	buf[len] = '\0';

	if (lenp)
		*lenp = len;

	return buf;
}

