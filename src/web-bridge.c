/*
 * Web interpreter bridge: exposes ucode as a WebAssembly module callable
 * from JavaScript. Replaces the native CLI's main().
 *
 * Public API (exported to JS via emscripten):
 *
 *   ucode_run(source)        run source as a ucode script
 *   ucode_eval(source)       run source as an expression, print result
 *   ucode_run_file(path)     run a file from the virtual filesystem
 *   ucode_render_file(path, template_mode)  run a file with its output
 *                            diverted to the render buffer (see below)
 *   ucode_reset()            drop the VM (globals, closures) and start fresh
 *   ucode_module_count()     number of statically linked modules
 *   ucode_version()          pointer to a NUL-terminated C string with the
 *                            ucode version the wasm was built from
 *                            (abbreviated commit + build date, baked in at
 *                            compile time via the UCODE_VERSION macro)
 *   ucode_get_output()       pointer to a NUL-terminated C string with all
 *                            output captured since the last call (stdout
 *                            only; C's stderr is captured separately in
 *                            Module.stderrText, see web-bridge.js);
 *                            empty string if none
 *   ucode_get_render()       likewise for the render buffer
 *   ucode_get_error()        pointer to a NUL-terminated C string with the
 *                            last compile/run error, or empty string
 *
 * Module preloading
 * -----------------
 * The statically linked modules (see web-bridge-modules.inc) are
 * registered in the global `modules` dictionary at VM init, and their
 * names are listed in the parse config's force_dynlink_list. The
 * compiler therefore emits a runtime lookup for `import ... from "math"`
 * (and friends) instead of a file search, and uc_require_path() checks
 * the `modules` dictionary before the search path, so require() of the
 * same names resolves to the preloaded objects. There is no dlopen under
 * wasm; this is the whole module-resolution story.
 *
 * Virtual filesystem (see "Project filesystem" below)
 * ---------------------------------------------------
 *
 *   ucode_vfs_write(path, data, len)  create/overwrite a file (len < 0 -> strlen)
 *   ucode_vfs_read(path)              file contents ("" if unreadable)
 *   ucode_vfs_remove(path)            unlink / rmdir
 *   ucode_vfs_clear(root)             recursive delete of a tree
 *   ucode_vfs_list(root)              JSON listing of a tree
 *
 * Output capture
 * --------------
 * Rather than relying on emscripten's TTY/stdout (which is unreliable for
 * C printf output after the module's initial run in MODULARIZE mode), all
 * ucode output is written to a growable C buffer owned by this bridge.
 * The ucode VM's `print()` and error reporting write to `vm->output`
 * (a FILE*). We point that at a memfd-free custom FILE* backed by
 * printbuf, and expose the buffer contents to JS after each run.
 */

